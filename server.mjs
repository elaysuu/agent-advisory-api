import http from 'node:http';
const ECOS=new Set(['npm','PyPI','Go','crates.io','Maven','NuGet','RubyGems','Packagist','Pub','Hex','Hackage','CRAN','GitHub Actions','Debian','Alpine','Ubuntu']);
const SECRET=process.env.RAPIDAPI_PROXY_SECRET||'';const PORT=+process.env.PORT||8080;
const cache=new Map(),TTL=600e3,hits=new Map(),RL=60;
const send=(s,c,o)=>{s.writeHead(c,{'content-type':'application/json'});s.end(JSON.stringify(o))};
export const handler=async(q,s)=>{const u=new URL(q.url,'http://x');
 if(u.pathname==='/health')return send(s,200,{ok:true});
 if(u.pathname!=='/check'||q.method!=='GET')return send(s,404,{error:'not found'});
 if(SECRET&&q.headers['x-rapidapi-proxy-secret']!==SECRET)return send(s,403,{error:'forbidden'});
 const ip=q.headers['x-rapidapi-user']||q.socket.remoteAddress,m=Math.floor(Date.now()/60e3),k=ip+m,n=(hits.get(k)||0)+1;hits.set(k,n);if(hits.size>1e4)hits.clear();
 if(n>RL)return send(s,429,{error:'rate limit 60/min'});
 const pkg=u.searchParams.get('pkg')||'',eco=u.searchParams.get('ecosystem')||'npm',ver=u.searchParams.get('version')||'';
 if(!/^[@\w.\/:+-]{1,214}$/.test(pkg))return send(s,400,{error:'invalid pkg'});
 if(!ECOS.has(eco))return send(s,400,{error:'invalid ecosystem',allowed:[...ECOS]});
 if(ver&&!/^[\w.+-]{1,64}$/.test(ver))return send(s,400,{error:'invalid version'});
 const ck=eco+'|'+pkg+'|'+ver,c=cache.get(ck);if(c&&Date.now()-c.t<TTL)return send(s,200,{...c.v,cached:true});
 try{const body={package:{name:pkg,ecosystem:eco}};if(ver)body.version=ver;
  const r=await fetch('https://api.osv.dev/v1/query',{method:'POST',body:JSON.stringify(body),signal:AbortSignal.timeout(8000)});
  if(!r.ok)return send(s,502,{error:'upstream '+r.status});const j=await r.json();
  const adv=(j.vulns||[]).map(x=>({id:x.id,aliases:x.aliases||[],summary:x.summary||null,severity:(x.database_specific||{}).severity||null,modified:x.modified,url:'https://osv.dev/vulnerability/'+x.id}));
  const v={pkg,ecosystem:eco,version:ver||null,count:adv.length,advisories:adv,source:'osv.dev',checked_at:new Date().toISOString()};
  cache.set(ck,{t:Date.now(),v});if(cache.size>5000)cache.clear();send(s,200,v);
 }catch(e){send(s,504,{error:'upstream timeout'})}};
if(!process.env.NO_LISTEN)http.createServer(handler).listen(PORT,()=>console.log('listening',PORT));
